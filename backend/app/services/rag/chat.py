logger = get_logger(__name__)


class ChatService:
    """Manages conversational memory, retrieval grounding, and streaming LLM executions."""

    def __init__(self) -> None:
        self.retriever = HybridRetriever()
        self.citation_engine = CitationEngine()
        self.openai_client = AsyncOpenAI(api_key=settings.OPENAI_API_KEY)

    async def stream_chat_response(
        self,
        session_id: uuid.UUID,
        user_id: uuid.UUID,
        message_content: str,
        *,
        document_ids: list[uuid.UUID] | None = None,
        multi_query: bool = False,
        expand_context: bool = False,
    ) -> AsyncGenerator[str, None]:
        """Orchestrates RAG stream using LangGraph, yielding node events and final tokens."""
        from app.services.agents.graph import build_agent_graph
        from langchain_core.messages import HumanMessage
        
        start_time = time.perf_counter()
        sanitized_content = PromptGuard.sanitize_query(message_content)
        
        # Save user query message to DB
        async with db_session.AsyncSessionLocal() as session:
            user_msg = ChatMessage(
                chat_id=session_id,
                role="user",
                content=sanitized_content,
            )
            session.add(user_msg)
            await session.commit()

        graph = build_agent_graph()
        
        initial_state = {
            "messages": [HumanMessage(content=sanitized_content)],
            "session_id": str(session_id),
            "user_id": str(user_id),
            "document_ids": [str(d) for d in document_ids] if document_ids else []
        }
        
        final_state = None
        
        try:
            # We use astream to stream graph execution events
            async for event in graph.astream(initial_state):
                for node_name, node_state in event.items():
                    # Yield node status to frontend
                    yield f"data: {json.dumps({'type': 'agent_state', 'node': node_name, 'status': 'completed'})}\\n\\n"
                    final_state = node_state
                    await asyncio.sleep(0.1)  # small buffer for visual effect in UI

            # After graph finishes, yield the actual final text generated by the composer/verifier
            if final_state and "final_response" in final_state:
                # We yield the entire block (or could mock a token stream here)
                # Since the reasoner generated it fully, we'll yield it as a single chunk for simplicity in this phase, 
                # or chunk it artificially to preserve the streaming UI effect.
                text = final_state["final_response"]
                # Artificial stream
                for i in range(0, len(text), 5):
                    chunk = text[i:i+5]
                    yield f"data: {json.dumps({'type': 'content', 'content': chunk})}\\n\\n"
                    await asyncio.sleep(0.01)

                citations = final_state.get("citations", [])
                yield f"data: {json.dumps({'type': 'citations', 'citations': citations})}\\n\\n"
                
                # Save assistant response
                async with db_session.AsyncSessionLocal() as session:
                    assistant_msg = ChatMessage(
                        chat_id=session_id,
                        role="assistant",
                        content=text,
                        citations=citations,
                    )
                    session.add(assistant_msg)
                    
                    # Log telemetry
                    total_duration_ms = int((time.perf_counter() - start_time) * 1000)
                    token_count = token_manager.count_tokens(text) + token_manager.count_tokens(message_content)
                    
                    usage_log = UsageLog(
                        user_id=user_id,
                        action="agent_completion",
                        token_count=token_count,
                        latency_ms=total_duration_ms,
                        cost=0.00015 * (token_count / 1000),
                        extra_info={
                            "session_id": str(session_id),
                            "citations_found": len(citations),
                            "confidence": final_state.get("confidence", 1.0)
                        },
                    )
                    session.add(usage_log)
                    await session.commit()

        except Exception as exc:
            logger.exception("LangGraph execution failed")
            yield f"data: {json.dumps({'type': 'error', 'message': str(exc)})}\\n\\n"
            
        yield "data: [DONE]\\n\\n"

    async def _load_conversation_history(self, session_id: uuid.UUID) -> list[tuple[str, str]]:
        """Load past messages for context, keeping memory bounded (last 8 turns)."""
        async with db_session.AsyncSessionLocal() as session:
            stmt = (
                select(ChatMessage)
                .where(ChatMessage.chat_id == session_id)
                .order_by(ChatMessage.created_at.desc())
                .limit(8)
            )
            result = await session.execute(stmt)
            messages = list(result.scalars().all())
            
        # Reverse to chronologically ascending order
        messages.reverse()
        return [(m.role, m.content) for m in messages]

